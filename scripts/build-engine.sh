#!/bin/sh
# Compiles the Spanish synonym engine (engine/src) and embeds it in src/synonyms/engine-jar.ts,
# so it ships inside main.js. Only needed after changing the Java code.
# LT is a LanguageTool folder to compile against; the plugin runs the engine with the
# LanguageTool the user has, any 6.x.
set -eu
cd "$(dirname "$0")/.."

LT=${LT:-/opt/languagetool/LanguageTool-6.4}
JAVA_HOME=${JAVA_HOME:-/opt/homebrew/opt/openjdk@21}

out=$(mktemp -d)
trap 'rm -rf "$out"' EXIT
mkdir -p "$out/classes"
"$JAVA_HOME/bin/javac" --release 17 -encoding UTF-8 -Xlint:all,-path,-processing,-classfile \
    -cp "$LT/languagetool-server.jar:$LT/libs/*" \
    -d "$out/classes" engine/src/local/ltsynonyms/*.java
"$JAVA_HOME/bin/jar" --create --file "$out/engine.jar" -C "$out/classes" .

{
    echo "// Generated by scripts/build-engine.sh from engine/src; do not edit."
    echo "// The Spanish synonym engine, a Java archive, in base64."
    echo "export const ENGINE_JAR ="
    printf '    "%s";\n' "$(base64 < "$out/engine.jar" | tr -d '\n')"
    printf 'export const ENGINE_JAR_SHA256 = "%s";\n' "$(shasum -a 256 "$out/engine.jar" | cut -d' ' -f1)"
} > src/synonyms/engine-jar.ts
echo "src/synonyms/engine-jar.ts: $(wc -c < "$out/engine.jar" | tr -d ' ') bytes of Java archive"
